"""Write the key numbers and the regional table of the report from the saved results.

Objective
    Keep the numbers in the LaTeX report identical to the analysis. The text never
    contains hand-copied values: it uses \\R{585}{SO}{dmean} etc., defined in
    report/generated/numbers.tex, which this script writes from
    data/processed/change/hs_regional_summary.csv (written by 01_change_signal).

Usage (from the project root, after running 01_change_signal for VAR = "hs"):
    .venv/bin/python src/make_report_numbers.py              # writes into report/generated/
    .venv/bin/python src/make_report_numbers.py --out other/dir

Then recompile the report (or upload the two generated files to Overleaf).
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCEN = {"SSP1-2.6": "126", "SSP5-8.5": "585"}
REGION = {  # region label starts with ... -> key used in the report
    "Global": "GL", "Southern Ocean": "SO", "Tropics": "TR", "North Pacific": "NP",
    "North Atlantic": "NA", "North Sea": "NS", "Arctic": "AR"}
COLS = {  # CSV column -> (key, decimals)
    "hist mean [m]": ("hmean", 2), "Δ mean [m]": ("dmean", 2), "Δ mean [%]": ("dmeanpct", 1),
    "hist p99 [m]": ("hpnn", 2), "Δ p99 [m]": ("dpnn", 2), "Δ p99 [%]": ("dpnnpct", 1),
    "significant [% area]": ("sig", 1), "masked [% area]": ("masked", 1)}
TABLE_REGIONS = ("GL", "SO", "TR", "NP", "NA", "NS", "AR")
NAMES = {"GL": "Global", "SO": "Southern Ocean (S of 45\\textdegree S)", "TR": "Tropics (15\\textdegree S--15\\textdegree N)",
         "NP": "North Pacific", "NA": "North Atlantic", "NS": "North Sea \\& Norwegian Sea",
         "AR": "Arctic (N of 66\\textdegree N)$^\\dagger$"}


def fmt(x: float, d: int, signed: bool) -> str:
    s = f"{x:+.{d}f}" if signed else f"{x:.{d}f}"
    s = s.replace("-0." + "0" * d, "0." + "0" * d).replace("+0." + "0" * d, "0." + "0" * d)
    return s.replace("-", "$-$").replace("+", "$+$") if signed else s


def region_key(label: str) -> str:
    for start, key in REGION.items():
        if label.startswith(start):
            return key
    raise SystemExit(f"unknown region '{label}': add it to REGION")


def ssp_period() -> str:
    """Period of the SSP statistics used ('2071-2100', or '2071-2098' before the repair)."""
    try:
        sys.path.insert(0, str(ROOT / "src"))
        from compute_stats import load_stats
        p = {load_stats(s, "hs", "best")["period"] for s in ("ssp126", "ssp585")}
        return p.pop() if len(p) == 1 else "MIXED"
    except Exception:
        return "2071-2100"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--csv", default=ROOT / "data/processed/change/hs_regional_summary.csv", type=Path)
    ap.add_argument("--out", default=ROOT / "report/generated", type=Path)
    ap.add_argument("--period", default=None, help="SSP period; default: read from the statistics")
    a = ap.parse_args()

    with open(a.csv, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    vals = {}
    for r in rows:
        s, g = SCEN[r["scenario"]], region_key(r["region"])
        for col, (key, d) in COLS.items():
            signed = key.startswith("d")
            vals[(s, g, key)] = fmt(float(r[col]), d, signed)
            if signed:  # unsigned magnitude for running text ("decreases by 0.20 m")
                vals[(s, g, key + "abs")] = fmt(abs(float(r[col])), d, False)
    period = a.period or ssp_period()

    a.out.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by src/make_report_numbers.py from " + a.csv.name + " -- do not edit by hand.",
             f"\\newcommand{{\\SSPperiod}}{{{period.replace('-', '--')}}}",
             f"\\newcommand{{\\SSPyears}}{{{int(period[-4:]) - int(period[:4]) + 1 if period[:4].isdigit() else 30}}}"]
    lines += [f"\\expandafter\\def\\csname r@{s}@{g}@{k}\\endcsname{{{v}}}" for (s, g, k), v in sorted(vals.items())]
    ice_csv = a.csv.with_name("ice_affected_area.csv")     # optional, from section 6 of 01_change_signal
    if ice_csv.exists():
        with open(ice_csv, encoding="utf-8") as fh:
            for r in csv.DictReader(fh):
                sc = {"historical": "hist", **SCEN}[r["scenario"]]
                area, chg = float(r["ice-affected area [Mkm2]"]), float(r["change vs historical [%]"])
                for k, v in (("area", f"{area:.1f}"), ("chg", fmt(chg, 0, True)), ("chgabs", f"{abs(chg):.0f}")):
                    lines.append(f"\\expandafter\\def\\csname ice@{sc}@{r['hemisphere']}@{k}\\endcsname{{{v}}}")
    else:
        print(f"note: {ice_csv.name} not found - ice numbers in the report stay '??'")
    (a.out / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    t = ["% Generated by src/make_report_numbers.py -- do not edit by hand.",
         "\\begin{tabular}{l rrr rrr r}", "\\toprule",
         " & \\multicolumn{3}{c}{Mean $H_s$} & \\multicolumn{3}{c}{99th percentile $H_s$} & Signif. \\\\",
         "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
         "Region & hist.\\ [m] & $\\Delta$ [m] & $\\Delta$ [\\%] & hist.\\ [m] & $\\Delta$ [m] & $\\Delta$ [\\%] & [\\% area] \\\\",
         "\\midrule"]
    for s, label in (("126", "SSP1-2.6"), ("585", "SSP5-8.5")):
        t.append(f"\\multicolumn{{8}}{{l}}{{\\textit{{{label}}}}} \\\\")
        for g in TABLE_REGIONS:
            if (s, g, "dmean") not in vals:
                continue
            v = lambda k: vals[(s, g, k)]
            t.append(f"\\quad {NAMES[g]} & {v('hmean')} & {v('dmean')} & {v('dmeanpct')} & "
                     f"{v('hpnn')} & {v('dpnn')} & {v('dpnnpct')} & {v('sig')} \\\\")
        t.append("\\addlinespace")
    t[-1] = "\\bottomrule"
    t.append("\\end{tabular}")
    (a.out / "regional_table.tex").write_text("\n".join(t) + "\n", encoding="utf-8")
    print(f"wrote {a.out / 'numbers.tex'} and {a.out / 'regional_table.tex'} (SSP period {period})")


if __name__ == "__main__":
    main()
